"""Generate comprehensive integration tests for SAFT-VR Mie and SAFT-VRQ Mie."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/rust_port"))
from reference import load

load(str(ROOT / ".toolchains/gcc14/mingw64/bin"))
from thermopack.saftvrmie import saftvrmie

def generate_test_file():
    lines = []
    lines.append("// Integration tests for SAFT-VR Mie and SAFT-VRQ Mie.")
    lines.append("// Generated by tools/rust_port/generate_saftvrmie_tests.py against .reference/thermopack.dll.")
    lines.append("// Copyright thermotools and Contributors. Apache-2.0.\n")
    lines.append("use thermopack_rs::{SaftVrMie, Phase};\n")

    # 1. Pure CO2 tests
    print("Generating pure CO2 tests...")
    lines.append("#[test]")
    lines.append("fn test_saft_vrmie_pure_co2_states() {")
    lines.append('    let eos = SaftVrMie::new(&["CO2"]).expect("failed to load CO2");')
    lines.append("    assert_eq!(eos.num_components(), 1);\n")

    co2_eos = saftvrmie("CO2")
    co2_points = [
        (250.0, 50.0, "vapor"),
        (300.0, 5000.0, "subcritical dense gas"),
        (350.0, 15000.0, "supercritical dense fluid"),
    ]

    for T, rho, label in co2_points:
        V = 1.0 / rho
        P, dpdt, dpdv, dpdn = co2_eos.pressure_tv(T, V, [1.0], dpdt=True, dpdv=True, dpdn=True)
        lnphi, = co2_eos.thermo_tvp(T, V, [1.0])
        a_hs = co2_eos.a_hs(T, V, [1.0])
        a1 = co2_eos.a1(T, V, [1.0])
        a2 = co2_eos.a2(T, V, [1.0])
        a3 = co2_eos.a3(T, V, [1.0])

        lines.append(f"    // Point: T = {T} K, rho = {rho} mol/m^3 ({label})")
        lines.append(f"    let prep = eos.prepare({T:.1f}, &[1.0]).unwrap();")
        lines.append(f"    let terms = prep.helmholtz_terms({rho:.1f}).unwrap();")
        lines.append(f"    assert!((terms.a_hs - {a_hs:.16e}).abs() < 1e-12, \"a_hs diff: {{}}\", (terms.a_hs - {a_hs:.16e}).abs());")
        lines.append(f"    assert!((terms.a1 - {a1:.16e}).abs() < 1e-10, \"a1 diff: {{}}\", (terms.a1 - {a1:.16e}).abs());")
        lines.append(f"    assert!((terms.a2 - {a2:.16e}).abs() < 1e-8, \"a2 diff: {{}}\", (terms.a2 - {a2:.16e}).abs());")
        lines.append(f"    assert!((terms.a3 - {a3:.16e}).abs() < 1e-6, \"a3 diff: {{}}\", (terms.a3 - {a3:.16e}).abs());")
        p_tol = 1e-3 * max(1.0, abs(P))
        lines.append(f"    let jet = prep.pressure_and_derivatives({rho:.1f}).unwrap();")
        lines.append(f"    assert!((jet.pressure - {P:.16e}).abs() < {p_tol:.16e}, \"P diff: {{}}\", (jet.pressure - {P:.16e}).abs());")
        lines.append(f"    let st = prep.state({rho:.1f}).unwrap();")
        lines.append(f"    assert!((st.ln_phi[0] - {float(lnphi[0]):.16e}).abs() < 1e-5, \"lnphi diff: {{}}\", (st.ln_phi[0] - {float(lnphi[0]):.16e}).abs());\n")

    lines.append("}\n")

    # 2. Pure CO2 volume roots and saturation
    print("Generating pure CO2 volume and saturation tests...")
    p_sat, _ = co2_eos.bubble_pressure(280.0, [1.0])
    vl_sat, = co2_eos.specific_volume(280.0, p_sat, [1.0], co2_eos.LIQPH)
    vv_sat, = co2_eos.specific_volume(280.0, p_sat, [1.0], co2_eos.VAPPH)

    lines.append("#[test]")
    lines.append("fn test_saft_vrmie_pure_co2_volume_and_saturation() {")
    lines.append('    let eos = SaftVrMie::new(&["CO2"]).expect("failed to load CO2");')
    lines.append("    let prep = eos.prepare(280.0, &[1.0]).unwrap();")
    lines.append("    let p_target = 2.0e6; // 20 bar")
    lines.append("    let vv = prep.volume(p_target, Phase::Vapor).unwrap();")
    lines.append("    let jet_v = prep.pressure_and_derivatives(1.0 / vv).unwrap();")
    lines.append("    assert!((jet_v.pressure - p_target).abs() < 1e-2);")
    lines.append("    let vl = prep.volume(p_target, Phase::Liquid).unwrap();")
    lines.append("    let jet_l = prep.pressure_and_derivatives(1.0 / vl).unwrap();")
    lines.append("    assert!((jet_l.pressure - p_target).abs() < 1e-2);")
    lines.append("    assert!(vl < vv);\n")

    lines.append(f"    // Saturation pressure at 280 K: reference P_sat = {p_sat:.6e} Pa")
    lines.append("    let sat = prep.saturation_pressure(280.0).unwrap();")
    lines.append(f"    assert!((sat.pressure - {p_sat:.8e}).abs() / {p_sat:.8e} < 1e-3, \"sat P diff: {{}}\", (sat.pressure - {p_sat:.8e}).abs());")
    lines.append(f"    assert!((sat.liquid_volume - {vl_sat:.8e}).abs() / {vl_sat:.8e} < 1e-2);")
    lines.append(f"    assert!((sat.vapor_volume - {vv_sat:.8e}).abs() / {vv_sat:.8e} < 1e-2);")
    lines.append("}\n")

    # 3. Pure C1 tests
    print("Generating pure C1 tests...")
    lines.append("#[test]")
    lines.append("fn test_saft_vrmie_pure_c1_states() {")
    lines.append('    let eos = SaftVrMie::new(&["C1"]).expect("failed to load C1");')
    c1_eos = saftvrmie("C1")
    c1_points = [
        (150.0, 50.0, "gas"),
        (200.0, 2000.0, "dense gas"),
        (300.0, 10000.0, "dense supercritical"),
    ]
    for T, rho, label in c1_points:
        V = 1.0 / rho
        P, dpdt, dpdv, dpdn = c1_eos.pressure_tv(T, V, [1.0], dpdt=True, dpdv=True, dpdn=True)
        lnphi, = c1_eos.thermo_tvp(T, V, [1.0])
        lines.append(f"    // T = {T} K, rho = {rho} mol/m^3 ({label})")
        lines.append(f"    let prep = eos.prepare({T:.1f}, &[1.0]).unwrap();")
        p_tol = 1e-3 * max(1.0, abs(P))
        lines.append(f"    let jet = prep.pressure_and_derivatives({rho:.1f}).unwrap();")
        lines.append(f"    assert!((jet.pressure - {P:.16e}).abs() < {p_tol:.16e});")
        lines.append(f"    let st = prep.state({rho:.1f}).unwrap();")
        lines.append(f"    assert!((st.ln_phi[0] - {float(lnphi[0]):.16e}).abs() < 1e-5);\n")
    lines.append("}\n")

    # 4. Binary mixture CO2 + C1
    print("Generating binary mixture CO2 + C1 tests...")
    lines.append("#[test]")
    lines.append("fn test_saft_vrmie_binary_co2_c1() {")
    lines.append('    let eos = SaftVrMie::new(&["CO2", "C1"]).expect("failed to load CO2,C1");')
    lines.append("    assert_eq!(eos.num_components(), 2);")
    lines.append("    assert!((eos.get_kij(0, 1) - 0.0573).abs() < 1e-5);")
    lines.append("    assert!((eos.get_lij(0, 1) - (-0.0101)).abs() < 1e-5);\n")

    mix_eos = saftvrmie("CO2,C1")
    T_mix = 280.0
    V_mix = 0.0002
    n_mix = [0.4, 0.6]
    rho_mix = 1.0 / V_mix
    P_mix, _, _, _ = mix_eos.pressure_tv(T_mix, V_mix, n_mix, dpdt=True, dpdv=True, dpdn=True)
    lnphi_mix, = mix_eos.thermo_tvp(T_mix, V_mix, n_mix)

    lines.append(f"    let prep = eos.prepare({T_mix:.1f}, &[{n_mix[0]}, {n_mix[1]}]).unwrap();")
    lines.append(f"    let jet = prep.pressure_and_derivatives({rho_mix:.1f}).unwrap();")
    lines.append(f"    assert!((jet.pressure - {P_mix:.16e}).abs() < 1e-3 * {P_mix:.16e});")
    lines.append(f"    let st = prep.state({rho_mix:.1f}).unwrap();")
    lines.append(f"    assert!((st.ln_phi[0] - {float(lnphi_mix[0]):.16e}).abs() < 1e-4);")
    lines.append(f"    assert!((st.ln_phi[1] - {float(lnphi_mix[1]):.16e}).abs() < 1e-4);")
    lines.append("}\n")

    # 5. Quantum fluid tests (H2)
    print("Generating quantum fluid H2 tests...")
    lines.append("#[test]")
    lines.append("fn test_saft_vrmie_quantum_h2() {")
    lines.append('    let eos = SaftVrMie::new(&["H2"]).expect("failed to load H2");')
    h2_eos = saftvrmie("H2")
    h2_points = [
        (30.0, 100.0),
        (50.0, 2000.0),
        (100.0, 8000.0),
    ]
    for T, rho in h2_points:
        V = 1.0 / rho
        P, _, _, _ = h2_eos.pressure_tv(T, V, [1.0], dpdt=True, dpdv=True, dpdn=True)
        lnphi, = h2_eos.thermo_tvp(T, V, [1.0])
        lines.append(f"    let prep = eos.prepare({T:.1f}, &[1.0]).unwrap();")
        p_tol = 1e-3 * max(1.0, abs(P))
        lines.append(f"    let jet = prep.pressure_and_derivatives({rho:.1f}).unwrap();")
        lines.append(f"    assert!((jet.pressure - {P:.16e}).abs() < {p_tol:.16e});")
        lines.append(f"    let st = prep.state({rho:.1f}).unwrap();")
        lines.append(f"    assert!((st.ln_phi[0] - {float(lnphi[0]):.16e}).abs() < 1e-5);\n")
    lines.append("}\n")

    # Write output file
    target_path = ROOT / "tests/saft_vrmie.rs"
    target_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {target_path} successfully!")

if __name__ == "__main__":
    generate_test_file()
