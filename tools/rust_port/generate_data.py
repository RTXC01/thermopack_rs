"""Generate Rust constants from compiled databases and JSON aliases."""
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def number(value):
    value = float(value)
    assert value == value and abs(value) != float("inf")
    return repr(value)


def string(value):
    return json.dumps(str(value), ensure_ascii=False)


def compiled_components(path):
    source = path.read_text(encoding='utf-8')
    general, heat_capacity = {}, {}
    for datatype, output in [('gendatadb', general), ('cpdata', heat_capacity)]:
        for block in re.findall(datatype + r'\((.*?)^\s*\)', source, re.M | re.S):
            values = dict(re.findall(r'(\w+)\s*=\s*"([^"]*)"', block))
            for key, value in re.findall(r'\b(\w+)\s*=\s*([+-]?[\d.]+(?:[eEdD][+-]?\d+)?)', block):
                values[key] = float(value.replace('D', 'e').replace('d', 'e'))
            if datatype == 'cpdata':
                if 'DEFAULT' not in values['ref'].upper():
                    continue
                array = re.search(r'\bcp\s*=\s*\(/(.*?)/\)', block, re.S)[1]
                values['cp'] = [float(v.strip().replace('D', 'e').replace('d', 'e'))
                                for v in array.replace('&', '').split(',')]
                assert len(values['cp']) == 21
            output[values['ident' if datatype == 'gendatadb' else 'cid']] = values
    return general, heat_capacity


def generate():
    lines = ["// Generated by tools/rust_port/generate_data.py; do not edit.",
             "// Copyright thermotools and Contributors. Apache-2.0.",
             "pub(super) const COMPONENTS: &[Component] = &["]
    inputs = sorted((ROOT / "fluids").glob("*.json"))
    compiled_path = ROOT / 'src/compdatadb.f90'
    general, heat_capacity = compiled_components(compiled_path)
    for path in inputs:
        data = json.loads(path.read_text(encoding="utf-8"))
        baseline = general[data['ident']]
        cp = heat_capacity.get(data['ident'])
        coefficients = cp["cp"] if cp else []
        assert len(coefficients) <= 21
        coefficients = coefficients + [0] * (21 - len(coefficients))
        lines.append("Component { " + ", ".join([
            "ident: " + string(data["ident"]), "name: " + string(data["name"]),
            "aliases: &[" + ", ".join(map(string, data.get("aliases", []))) + "]",
            "molar_mass: " + number(baseline['mw']),
            "critical_temperature: " + number(baseline['Tc']),
            "critical_pressure: " + number(baseline['Pc']),
            "acentric_factor: " + number(baseline['acf']),
            "cp_type: " + str(int(cp['cptype']) if cp else 0),
            "cp: [" + ", ".join(map(number, coefficients)) + "]",
            "reference_enthalpy: " + number(baseline['href']),
            "reference_entropy: " + number(baseline['sref']),
            "reference_pressure: " + number(101325 if baseline['sref_state'] == '1ATM' else 100000),
        ]) + " },")
    inputs.append(compiled_path)
    lines.extend(["];", "pub(super) const INTERACTIONS: &[Interaction] = &["])
    # Compiled parameters are authoritative: JSON and generated Fortran can
    # differ. Duplicate CO2/H2O defaults require last-default-wins selection.
    path = ROOT / "src/mixdatadb.f90"
    inputs.append(path)
    source = path.read_text(encoding="utf-8")
    for datatype, covolume in [("kijdatadb", False), ("lijdatadb", True)]:
        for block in re.findall(datatype + r"\((.*?)^\s*\)", source, re.M | re.S):
            values = dict(re.findall(r'(\w+)\s*=\s*"([^"]*)"', block))
            if values["eosid"] not in ("PR", "SRK") or values["mruleid"].upper() != "VDW" \
                    or "DEFAULT" not in values["ref"].upper():
                continue
            value = re.search(r"[kl]ijvalue\s*=\s*([\d.eEdD+-]+)", block)[1]
            lines.append("Interaction { eos: " + string(values["eosid"])
                         + ", first: " + string(values["uid1"])
                         + ", second: " + string(values["uid2"]) + ", value: "
                         + number(value.replace("D", "e").replace("d", "e"))
                         + ", covolume: " + str(covolume).lower() + " },")
    lines.extend(["];", "pub(super) const ALPHA_RECORDS: &[AlphaRecord] = &["])
    counters = {'twu': 0, 'mc': 0}
    source = compiled_path.read_text(encoding='utf-8')
    pattern = r'type\s*\(alphadatadb\),\s*parameter\s*::\s*(twu|mc)(\d+)\s*=\s*&\s*alphadatadb\((.*?)^\s*\)'
    for family, index, block in re.findall(pattern, source, re.M | re.S | re.I):
        family = family.lower()
        counters[family] += 1
        assert int(index) == counters[family], 'Alpha constructor order differs from database order'
        values = dict(re.findall(r'(\w+)\s*=\s*"([^"]*)"', block))
        coeffs = re.search(r'coeff\s*=\s*\(/(.*?)/\)', block, re.S)[1]
        coefficients = [number(v.strip().replace('D', 'e').replace('d', 'e'))
                        for v in coeffs.replace('&', '').split(',')]
        assert len(coefficients) == 3
        lines.append('AlphaRecord { eos: '+string(values['eosid'])+', component: '
                     +string(values['cid'])+', reference: '+string(values['ref'])
                     +', mathias_copeman: '+str(family=='mc').lower()+', parameters: ['
                     +', '.join(coefficients)+'] },')
    assert counters['twu'] > 0 and counters['mc'] > 0
    lines.append("];")
    for path in inputs:
        lines.append("// " + path.relative_to(ROOT).as_posix() + " sha256="
                     + hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest())
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    (ROOT / "rust/src/data.rs").write_text(generate(), encoding="utf-8")
