"""Generate deterministic Rust constants from the fork's JSON database."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def number(value):
    value = float(value)
    assert value == value and abs(value) != float("inf")
    return repr(value)


def string(value):
    return json.dumps(str(value), ensure_ascii=False)


def generate():
    lines = ["// Generated by tools/rust_port/generate_data.py; do not edit.",
             "// Copyright thermotools and Contributors. Apache-2.0.",
             "pub(super) const COMPONENTS: &[Component] = &["]
    inputs = sorted((ROOT / "fluids").glob("*.json"))
    for path in inputs:
        data = json.loads(path.read_text())
        cps = [v for k, v in data.items() if k.startswith("ideal_heat_capacity")]
        cp = next((v for v in cps if "DEFAULT" in v["ref"].upper()), None)
        coefficients = cp["cp"] if cp else []
        assert len(coefficients) <= 21
        coefficients = coefficients + [0] * (21 - len(coefficients))
        ref = data.get("reference_state", {})
        lines.append("Component { " + ", ".join([
            "ident: " + string(data["ident"]), "name: " + string(data["name"]),
            "aliases: &[" + ", ".join(map(string, data.get("aliases", []))) + "]",
            "molar_mass: " + number(data["mol_weight"]),
            "critical_temperature: " + number(data["critical"]["temperature"]),
            "critical_pressure: " + number(data["critical"]["pressure"]),
            "acentric_factor: " + number(data["acentric_factor"]["acf"]),
            "cp_type: " + str(cp["correlation"] if cp else 0),
            "cp: [" + ", ".join(map(number, coefficients)) + "]",
            "reference_enthalpy: " + number(ref.get("enthalpy", 0)),
            "reference_entropy: " + number(ref.get("entropy", 0)),
            "reference_pressure: " + number(101325 if ref.get("entropy_ref_state") == "1ATM" else 100000),
        ]) + " },")
    lines.extend(["];", "pub(super) const INTERACTIONS: &[Interaction] = &["])
    for eos, filename, covolume in [("PR", "PR_kij.json", False),
                                   ("SRK", "SRK_kij.json", False),
                                   ("PR", "PR_lij.json", True)]:
        path = ROOT / "binaries" / filename
        inputs.append(path)
        for key, value in json.loads(path.read_text()).items():
            if not key.startswith("vdW") or "DEFAULT" not in value["ref"].upper():
                continue
            lines.append("Interaction { eos: " + string(eos) + ", first: " + string(value["comp1"])
                         + ", second: " + string(value["comp2"]) + ", value: "
                         + number(value["lij" if covolume else "kij"])
                         + ", covolume: " + str(covolume).lower() + " },")
    lines.append("];")
    for path in inputs:
        lines.append("// " + path.relative_to(ROOT).as_posix() + " sha256="
                     + hashlib.sha256(path.read_bytes()).hexdigest())
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    (ROOT / "rust/src/data.rs").write_text(generate(), encoding="utf-8")
