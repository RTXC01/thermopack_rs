"""Embed every MBWR record and the original pressure-term schema, in source order."""
import hashlib
import json
import re
import ast
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]


def records():
    source=(ROOT/'src/mbwrdata.f90').read_text()
    source=re.sub(r'!.*','',source)
    pattern=r'type\s*\(mbwr(19|32)Data\)\s*,\s*parameter\s*::\s*(\w+)\s*=\s*mbwr\d+Data\((.*?)^\s*\)'
    result=[]
    for family,name,block in re.findall(pattern,source,re.I|re.S|re.M):
        header,coefficients=block.split('(/',1)
        fields=[s.strip() for s in header.replace('&','').split(',') if s.strip()]
        assert len(fields)==6,(name,fields)
        values=[float(s.strip().replace('D','e').replace('d','e')) for s in coefficients.split('/)')[0].replace('&','').split(',')]
        assert len(values)==int(family)+1 and int(fields[-1])==len(values)
        result.append(dict(kind=int(family),source_name=name,identifier=fields[1].strip('"'),equation_number=int(fields[0]),
                           set_number=int(fields[2]),low_property=int(fields[3]),high_property=int(fields[4]),parameters=values))
    assert len(result)==65 and sum(r['kind']==19 for r in result)==54 and sum(r['kind']==32 for r in result)==11
    for kind in [19,32]:
        array=re.search(r'mbwr'+str(kind)+r'Array\s*=\s*\(/(.*?)/\)',source,re.S|re.I)[1]
        assert re.findall(r'mbwrcx\d+',array,re.I)==[r['source_name'] for r in result if r['kind']==kind]
    return result


def schema(kind):
    source=(ROOT/'src/mbwr.f90').read_text()
    body=re.search(r'subroutine fillIJL'+str(kind)+r'\(NIJL\)(.*?)end subroutine fillIJL'+str(kind),source,re.S|re.I)[1]
    values=[]
    for field in ['I','J','L']:
        entries=re.findall(r'NIJL%'+field+r'\((\d+)\)\s*=\s*([+\-\d.eE]+)',body,re.I)
        assert [int(i) for i,_ in entries]==list(range(1,kind+1))
        values.append([float(v) for _,v in entries])
    return list(zip(*values))


def stored_properties():
    """Read only explicit tables; missing entries are not estimated here."""
    source=(ROOT/'src/mbwrdata.f90').read_text()
    def table(name):
        values=re.search(r'::\s*'+name+r'\s*=\s*\(/(.*?)/\)',source,re.S|re.I)[1]
        return [float(s.strip()) for s in values.replace('&','').split(',') if s.strip()]
    result=[]
    for suffix,function in [('19','getMBWR19critPropIndex'),('32','getMBWR32critPropIndex'),('triple','getTriplePointPropIndex')]:
        body=re.search(r'function '+function+r'\(.*?end function '+function,source,re.S|re.I)[0]
        identifiers=re.findall(r'case\("([^"]+)"\)\s*index\s*=\s*(\d+)',body,re.I)
        arrays=[table(prefix+suffix+'_computed') for prefix in ['tc','pc','rc']] if suffix!='triple' else [table('tTriple_coolprop'),table('pTriple_coolprop')]
        for identifier,index in identifiers:
            result.append((suffix,identifier,[a[int(index)-1] for a in arrays]))
    return result


def generate():
    data=records()
    lines=['// Generated by tools/rust_port/generate_mbwr_data.py; do not edit.',
           '// Copyright thermotools and Contributors. Apache-2.0.',
           'use super::{MbwrKind, MbwrRecord, Term, MbwrHelmholtzTerm, R};','pub(super) const RECORDS: &[MbwrRecord] = &[']
    for r in data:
        fields=['kind: MbwrKind::'+('Bender19' if r['kind']==19 else 'Mbwr32')]
        fields += [name+': '+json.dumps(r[name]) for name in ['source_name','identifier','equation_number','set_number','low_property','high_property']]
        fields += ['parameters: &['+','.join(map(repr,r['parameters']))+']']
        lines.append('MbwrRecord {'+', '.join(fields)+'},')
    lines.append('];')
    for kind in [19,32]:
        lines.append(f'pub(super) const TERMS_{kind}: &[Term] = &[')
        for i,j,l in schema(kind):
            lines.append(f'Term {{ density_power: {int(i)}, temperature_power: {j!r}, exponential: {str(l!=0).lower()} }},')
        lines.append('];')
    lines.append('pub(super) const STORED_PROPERTIES: &[(u8, &str, [f64;3])] = &[')
    for family,identifier,values in stored_properties():
        if family=='triple': values.append(0.)
        lines.append('('+('0' if family=='triple' else family)+','+json.dumps(identifier)+','+repr(values)+'),')
    lines.append('];')
    lines+=source_helmholtz_function()
    path=ROOT/'rust/src/mbwr_data.rs'
    path.write_text('\n'.join(lines)+'\n')
    inputs=[ROOT/'src/mbwrdata.f90',ROOT/'src/mbwr.f90']
    (ROOT/'docs/rust/mbwr-data.json').write_text(json.dumps(dict(generator='tools/rust_port/generate_mbwr_data.py',records=65,
        mbwr19_records=54,mbwr32_records=11,source_sha256={p.relative_to(ROOT).as_posix():hashlib.sha256(p.read_bytes().replace(b'\r\n',b'\n')).hexdigest() for p in inputs},
        order='original mbwrcx declaration/array order; new(kind,identifier) selects first matching record, including three MBWR32 methane fits'),indent=2)+'\n')
    print('Generated 65 MBWR records and 19/32 pressure-term schemas')


def rust_expression(expression):
    expression=re.sub(r'(?:Z|Helm)%N\((\d+)\)',lambda m:('z' if m[0].startswith('Z') else 'h')+'['+str(int(m[1])-1)+']',expression)
    expression=re.sub(r'(\d+)\.[eE]([+-]?\d+)',r'\1.0e\2',expression)
    def convert(node):
        if isinstance(node,ast.Name):return node.id
        if isinstance(node,ast.Constant):return repr(float(node.value))
        if isinstance(node,ast.Subscript):return node.value.id+'['+str(node.slice.value)+']'+('.coefficient' if node.value.id=='h' else '')
        if isinstance(node,ast.UnaryOp):
            if isinstance(node.op,ast.USub):return '-('+convert(node.operand)+')'
            if isinstance(node.op,ast.UAdd):return '+('+convert(node.operand)+')'
            raise ValueError(ast.dump(node))
        if isinstance(node,ast.BinOp):
            if isinstance(node.op,ast.Pow):
                # Preserve the original gfortran multiplication chains, whose
                # final ulps are amplified by dilute integrated-term cancellation.
                if isinstance(node.left,ast.Name) and node.left.id=='gamma' and node.right.value==5:
                    return '(gamma.powi(2)*gamma.powi(3))'
                if isinstance(node.left,ast.Name) and node.left.id=='gamma' and node.right.value==6:
                    return '(gamma.powi(3)*gamma.powi(3))'
                return convert(node.left)+'.powi('+str(int(node.right.value))+')'
            op={ast.Add:'+',ast.Sub:'-',ast.Mult:'*',ast.Div:'/'}[type(node.op)]
            return '('+convert(node.left)+op+convert(node.right)+')'
        raise ValueError(ast.dump(node))
    return convert(ast.parse(expression.strip(),mode='eval').body)


def source_helmholtz_function():
    source=(ROOT/'src/mbwr.f90').read_text()
    body=source.split('! Integration of the exponential part')[1].split('Helm%J = -Helm%J')[0]
    blocks=[body.split('ELSE IF')[0],body.split('ELSE IF')[1]]
    lines=['// Parentheses preserve the original expression tree and arithmetic order.',
           '#[allow(unused_parens,clippy::neg_multiply)]',
           'pub(super) fn source_helmholtz(kind: MbwrKind, coefficients: &[f64], gamma: f64) -> ([MbwrHelmholtzTerm;40],usize) {',
           'let mut z=[0.0;32];',
           'for (i,&n) in coefficients.iter().enumerate() { z[i]=if kind==MbwrKind::Bender19 {n*1000.0/(1000.0*R)} else {n/(1000.0*R)}; }',
           'if kind==MbwrKind::Bender19 {for v in &mut z[1..5] {*v = -*v;}}',
           'let mut h=[MbwrHelmholtzTerm::default();40];',
           'let polynomial=if kind==MbwrKind::Bender19 {13}else{19};',
           'for (i,term) in kind.terms().iter().take(polynomial).enumerate() { h[i]=MbwrHelmholtzTerm {coefficient:z[i]/(term.density_power-1) as f64,density_power:(term.density_power-1) as i32,temperature_power:term.temperature_power-1.0,exponential:false}; }',
           'if kind==MbwrKind::Bender19 {']
    for index,block in enumerate(blocks):
        block=re.sub(r'!.*','',block).replace('&\n',' ').replace('&','')
        assignments=re.findall(r'Helm%([NIJL])\((\d+)\)\s*=\s*([^\n]+)',block)
        assert len(assignments)==(36 if index==0 else 84),len(assignments)
        for field,i,expression in assignments:
            target='h['+str(int(i)-1)+']'
            if field=='N':lines.append(target+'.coefficient = '+rust_expression(expression)+';')
            elif field=='I':lines.append(target+'.density_power = '+str(int(expression))+';')
            elif field=='J':lines.append(target+'.temperature_power = '+repr(-float(expression))+';')
            else:lines.append(target+'.exponential = '+str(int(expression)!=0).lower()+';')
        if index==0:lines.append('} else {')
    lines+=['}', '(h,if kind==MbwrKind::Bender19 {22}else{40})','}']
    return lines


if __name__=='__main__':generate()
