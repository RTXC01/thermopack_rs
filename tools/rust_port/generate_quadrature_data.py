"""Generate the Rust quadrature tables from the Fortran source of the fork.

The source stores the nodes and the weights of the Gauss and the
Gauss-Kronrod quadratures as parameter arrays in `src/quadratures.f90`. The
script parses those arrays and writes them into a Rust module that the native
quadrature module uses.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src/quadratures.f90"
TARGET = ROOT / "rust/src/quadrature_data.rs"

# The arrays of the source and the Rust name of each of them.
ARRAYS = [
    ("w_G10", "GAUSS_10_WEIGHTS"),
    ("x_K21", "KRONROD_21_NODES"),
    ("w_K21", "KRONROD_21_WEIGHTS"),
    ("w_G15", "GAUSS_15_WEIGHTS"),
    ("x_K31", "KRONROD_31_NODES"),
    ("w_K31", "KRONROD_31_WEIGHTS"),
    ("w_G20", "GAUSS_20_WEIGHTS"),
    ("x_K41", "KRONROD_41_NODES"),
    ("w_K41", "KRONROD_41_WEIGHTS"),
    ("w_G25", "GAUSS_25_WEIGHTS"),
    ("x_K51", "KRONROD_51_NODES"),
    ("w_K51", "KRONROD_51_WEIGHTS"),
    ("w_G30", "GAUSS_30_WEIGHTS"),
    ("x_K61", "KRONROD_61_NODES"),
    ("w_K61", "KRONROD_61_WEIGHTS"),
    ("w_G40", "GAUSS_40_WEIGHTS"),
    ("x_K81", "KRONROD_81_NODES"),
    ("w_K81", "KRONROD_81_WEIGHTS"),
    ("w_G50", "GAUSS_50_WEIGHTS"),
    ("x_K101", "KRONROD_101_NODES"),
    ("w_K101", "KRONROD_101_WEIGHTS"),
]


def number(value):
    value = float(value)
    assert value == value and abs(value) != float("inf")
    return repr(value)


def parse(source):
    text = source.read_text(encoding="utf-8")
    values = {}
    for name, _ in ARRAYS:
        match = re.search(
            r"\b" + name + r"\s*\([^)]*\)\s*=\s*\(/([^)]*?)/\)", text, re.S
        )
        assert match, name
        entries = [
            float(value.strip().replace("D", "e").replace("d", "e"))
            for value in match.group(1).replace("&", "").split(",")
            if value.strip()
        ]
        assert entries, name
        values[name] = entries
    return values


def generate():
    values = parse(SOURCE)
    lines = [
        "// Generated by tools/rust_port/generate_quadrature_data.py; do not edit.",
        "// Copyright thermotools and Contributors. Apache-2.0.",
        "//! The nodes and the weights of the Gauss and the Gauss-Kronrod",
        "//! quadratures of the source, in the order of the source arrays.",
        "",
    ]
    for name, rust_name in ARRAYS:
        entries = values[name]
        lines.append(
            "pub(super) const " + rust_name + ": [f64; " + str(len(entries)) + "] = ["
        )
        for index in range(0, len(entries), 3):
            chunk = entries[index : index + 3]
            lines.append("    " + ", ".join(number(value) for value in chunk) + ",")
        lines.append("];")
        lines.append("")
    TARGET.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote " + str(TARGET.relative_to(ROOT)))


if __name__ == "__main__":
    generate()
