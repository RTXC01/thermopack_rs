"""Generate Rust constants for SAFT-VR Mie pure component and binary interaction data."""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]


def number(value):
    v = float(value)
    return repr(v)


def string(value):
    return json.dumps(str(value))


def parse_db():
    source = (ROOT / "src/saftvrmie_datadb.f90").read_text(encoding="utf-8")

    pure_records = []
    for var, body in re.findall(r"(Miecx\d+)\s*=\s*&?\s*saftvrmie_data\((.*?)\n\s*\)", source, re.S):
        clean_body = re.sub(r"!\s*.*", "", body)
        clean_body = re.sub(r"&\s*[\r\n]+\s*(&)?", " ", clean_body)
        fields = {}
        for k, v in re.findall(r'(\w+)\s*=\s*("[^"]*"|[^,)]+)', clean_body):
            val = v.split('&')[0].strip()
            fields[k.strip().lower()] = val
        comp = fields.get("compname", "").strip('"')
        m_val = float(fields["m"])
        sigma_val = float(fields["sigma"])
        eps_val = float(fields["eps_depth_divk"])
        lambda_a_val = float(fields["lambda_a"])
        lambda_r_val = float(fields["lambda_r"])
        mass_val = float(fields.get("mass", "0.0"))
        fh_order_val = int(fields.get("fh_order", "0"))
        ref_val = fields.get("ref", "").strip('"')
        pure_records.append({
            "var": var,
            "ident": comp,
            "m": m_val,
            "sigma": sigma_val,
            "eps_depth_divk": eps_val,
            "lambda_a": lambda_a_val,
            "lambda_r": lambda_r_val,
            "mass": mass_val,
            "fh_order": fh_order_val,
            "scheme": "NoAssoc" if fields["assoc_scheme"] == "no_assoc" else
                      "Scheme" + fields["assoc_scheme"].split("_")[-1],
            "eps_assoc": float(fields["eps"]),
            "kab": float(fields["beta"]),
            "ref": ref_val,
        })

    kij_records = []
    for var, body in re.findall(r"(SVRM_KIJ_\d+)\s*=\s*&?\s*Miekijdata\((.*?)\n\s*\)", source, re.S):
        clean_body = re.sub(r"!\s*.*", "", body)
        clean_body = re.sub(r"&\s*[\r\n]+\s*(&)?", " ", clean_body)
        fields = {}
        for k, v in re.findall(r'(\w+)\s*=\s*("[^"]*"|[^,)]+)', clean_body):
            val = v.split('&')[0].strip()
            fields[k.strip().lower()] = val
        uid1 = fields.get("uid1", "").strip('"')
        uid2 = fields.get("uid2", "").strip('"')
        kij = float(fields["kijvalue"])
        ref_val = fields.get("ref", "").strip('"')
        kij_records.append({
            "var": var,
            "uid1": uid1,
            "uid2": uid2,
            "kij": kij,
            "ref": ref_val,
        })

    lij_records = []
    for var, body in re.findall(r"(SVRM_LIJ_\d+)\s*=\s*&?\s*Miekijdata\((.*?)\n\s*\)", source, re.S):
        clean_body = re.sub(r"!\s*.*", "", body)
        clean_body = re.sub(r"&\s*[\r\n]+\s*(&)?", " ", clean_body)
        fields = {}
        for k, v in re.findall(r'(\w+)\s*=\s*("[^"]*"|[^,)]+)', clean_body):
            val = v.split('&')[0].strip()
            fields[k.strip().lower()] = val
        uid1 = fields.get("uid1", "").strip('"')
        uid2 = fields.get("uid2", "").strip('"')
        lij = float(fields["kijvalue"])
        ref_val = fields.get("ref", "").strip('"')
        lij_records.append({
            "var": var,
            "uid1": uid1,
            "uid2": uid2,
            "lij": lij,
            "ref": ref_val,
        })

    return pure_records, kij_records, lij_records


def generate():
    pure, kij, lij = parse_db()
    lines = [
        "// Generated by tools/rust_port/generate_saftvrmie_data.py; do not edit.",
        "// Copyright thermotools and Contributors. Apache-2.0.",
        "",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct SaftVrMieRecord {",
        "    pub ident: &'static str,",
        "    pub m: f64,",
        "    pub sigma: f64,",
        "    pub eps_depth_divk: f64,",
        "    pub lambda_a: f64,",
        "    pub lambda_r: f64,",
        "    pub mass: f64,",
        "    pub fh_order: i32,",
        "    pub scheme: crate::association::AssocScheme,",
        "    pub eps_assoc_divk: f64,",
        "    pub kab: f64,",
        "    pub reference: &'static str,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct SaftVrMieKijRecord {",
        "    pub uid1: &'static str,",
        "    pub uid2: &'static str,",
        "    pub kij: f64,",
        "    pub reference: &'static str,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct SaftVrMieLijRecord {",
        "    pub uid1: &'static str,",
        "    pub uid2: &'static str,",
        "    pub lij: f64,",
        "    pub reference: &'static str,",
        "}",
        "",
        "pub(super) const PURE_RECORDS: &[SaftVrMieRecord] = &[",
    ]
    for r in pure:
        lines.append(
            f"    SaftVrMieRecord {{ ident: {string(r['ident'])}, m: {number(r['m'])}, "
            f"sigma: {number(r['sigma'])}, eps_depth_divk: {number(r['eps_depth_divk'])}, "
            f"lambda_a: {number(r['lambda_a'])}, lambda_r: {number(r['lambda_r'])}, "
            f"mass: {number(r['mass'])}, fh_order: {r['fh_order']}, "
            f"scheme: crate::association::AssocScheme::{r['scheme']}, "
            f"eps_assoc_divk: {number(r['eps_assoc'])}, kab: {number(r['kab'])}, "
            f"reference: {string(r['ref'])} }},"
        )
    lines.append("];")
    lines.append("")
    lines.append("pub(super) const KIJ_RECORDS: &[SaftVrMieKijRecord] = &[")
    for r in kij:
        lines.append(
            f"    SaftVrMieKijRecord {{ uid1: {string(r['uid1'])}, uid2: {string(r['uid2'])}, "
            f"kij: {number(r['kij'])}, reference: {string(r['ref'])} }},"
        )
    lines.append("];")
    lines.append("")
    lines.append("pub(super) const LIJ_RECORDS: &[SaftVrMieLijRecord] = &[")
    for r in lij:
        lines.append(
            f"    SaftVrMieLijRecord {{ uid1: {string(r['uid1'])}, uid2: {string(r['uid2'])}, "
            f"lij: {number(r['lij'])}, reference: {string(r['ref'])} }},"
        )
    lines.append("];")
    lines.append("")
    lines.append("""
pub fn lookup_pure(ident: &str, reference: Option<&str>) -> Option<SaftVrMieRecord> {
    let target_ref = reference.unwrap_or("DEFAULT");
    let mut default_match = None;
    for record in PURE_RECORDS {
        if record.ident.eq_ignore_ascii_case(ident) {
            let refs: Vec<&str> = record.reference.split('/').collect();
            for r in &refs {
                if r.eq_ignore_ascii_case(target_ref) {
                    return Some(*record);
                }
            }
            if default_match.is_none() && refs.iter().any(|r| r.eq_ignore_ascii_case("DEFAULT")) {
                default_match = Some(*record);
            }
        }
    }
    default_match
}

pub fn lookup_kij(uid1: &str, uid2: &str, reference: Option<&str>) -> f64 {
    let target_ref = reference.unwrap_or("DEFAULT");
    let mut default_match = None;
    for record in KIJ_RECORDS {
        let pair_match = (record.uid1.eq_ignore_ascii_case(uid1) && record.uid2.eq_ignore_ascii_case(uid2))
            || (record.uid1.eq_ignore_ascii_case(uid2) && record.uid2.eq_ignore_ascii_case(uid1));
        if pair_match {
            let refs: Vec<&str> = record.reference.split('/').collect();
            for r in &refs {
                if r.eq_ignore_ascii_case(target_ref) {
                    return record.kij;
                }
            }
            if default_match.is_none() && refs.iter().any(|r| r.eq_ignore_ascii_case("DEFAULT")) {
                default_match = Some(record.kij);
            }
        }
    }
    default_match.unwrap_or(0.0)
}

pub fn lookup_lij(uid1: &str, uid2: &str, reference: Option<&str>) -> f64 {
    let target_ref = reference.unwrap_or("DEFAULT");
    let mut default_match = None;
    for record in LIJ_RECORDS {
        let pair_match = (record.uid1.eq_ignore_ascii_case(uid1) && record.uid2.eq_ignore_ascii_case(uid2))
            || (record.uid1.eq_ignore_ascii_case(uid2) && record.uid2.eq_ignore_ascii_case(uid1));
        if pair_match {
            let refs: Vec<&str> = record.reference.split('/').collect();
            for r in &refs {
                if r.eq_ignore_ascii_case(target_ref) {
                    return record.lij;
                }
            }
            if default_match.is_none() && refs.iter().any(|r| r.eq_ignore_ascii_case("DEFAULT")) {
                default_match = Some(record.lij);
            }
        }
    }
    default_match.unwrap_or(0.0)
}
""")

    source = (ROOT / "src/saftvrmie_association.f90").read_text()
    coeff = {(int(i), int(j), int(k)): float(v) for i, j, k, v in re.findall(
        r"b\((\d+),(\d+),(\d+)\) = ([-+.0-9Ee]+)", source)}
    lines.append("// Dufal association integral: triangular (rho, T) powers, then lambda_r power.")
    lines.append("#[rustfmt::skip]")
    lines.append("pub(crate) const ASSOCIATION_B: [[f64; 7]; 66] = [")
    for i in range(11):
        for j in range(11 - i):
            row = ", ".join(number(coeff[i, j, k]) for k in range(7))
            lines.append(f"    [{row}],")
    lines.append("];")
    out_file = ROOT / "rust/src/saft_vrmie_data.rs"
    out_file.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(pure)} pure, {len(kij)} kij, and {len(lij)} lij records to {out_file}")


if __name__ == "__main__":
    generate()
