"""Generate tests/excess_gibbs.rs against .reference/thermopack.dll."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/rust_port"))
from reference import load

dll = load(str(ROOT / ".toolchains/gcc14/mingw64/bin"))
from thermopack.cubic import SoaveRedlichKwong, PengRobinson

lines = []
lines.append("//! Integration tests for Excess Gibbs / Huron-Vidal mixing rules.")
lines.append("//! Generated by tools/rust_port/generate_excess_gibbs_tests.py against .reference/thermopack.dll.")
lines.append("//! Copyright thermotools and Contributors. Apache-2.0.\n")
lines.append("#![allow(clippy::excessive_precision)]\n")
lines.append("use thermopack_rs::{Cubic, CubicKind, CubicOptions, MixingRule};\n")

# Test cases: (name, eos_class, kind_str, comps, mixing, T, V, z)
test_cases = [
    ("test_srk_c1_h2o_hv1", SoaveRedlichKwong, "SoaveRedlichKwong", "C1,H2O", "HV1", "HuronVidal1", "DEFAULT", [
        (300.0, 0.001, [0.5, 0.5]),
        (350.0, 0.0005, [0.8, 0.2]),
        (400.0, 0.0001, [0.2, 0.8]),
    ]),
    ("test_srk_c1_h2o_hv2", SoaveRedlichKwong, "SoaveRedlichKwong", "C1,H2O", "HV2", "HuronVidal2", "DEFAULT", [
        (300.0, 0.001, [0.5, 0.5]),
        (350.0, 0.0005, [0.8, 0.2]),
        (400.0, 0.0001, [0.2, 0.8]),
    ]),
    ("test_srk_co2_h2o_hv1", SoaveRedlichKwong, "SoaveRedlichKwong", "CO2,H2O", "HV1", "HuronVidal1", "DEFAULT", [
        (320.0, 0.001, [0.4, 0.6]),
        (380.0, 0.0002, [0.7, 0.3]),
    ]),
    ("test_srk_co2_h2o_hv2", SoaveRedlichKwong, "SoaveRedlichKwong", "CO2,H2O", "HV2", "HuronVidal2", "DEFAULT", [
        (320.0, 0.001, [0.4, 0.6]),
        (380.0, 0.0002, [0.7, 0.3]),
    ]),
    ("test_pr_h2o_meg_hv1", PengRobinson, "PengRobinson", "H2O,MEG", "HV1", "HuronVidal1", "Hemmingsen2011", [
        (350.0, 0.001, [0.7, 0.3]),
        (400.0, 0.0001, [0.5, 0.5]),
    ]),
    ("test_pr_h2s_c3_nrtl", PengRobinson, "PengRobinson", "H2S,C3", "NRTL", "Nrtl", "Dicko2012", [
        (300.0, 0.001, [0.4, 0.6]),
        (350.0, 0.0003, [0.7, 0.3]),
        (400.0, 0.0001, [0.2, 0.8]),
    ]),
    ("test_srk_c1_meg_hv1", SoaveRedlichKwong, "SoaveRedlichKwong", "C1,MEG", "HV1", "HuronVidal1", "DEFAULT", [
        (320.0, 0.001, [0.6, 0.4]),
        (380.0, 0.0003, [0.3, 0.7]),
    ]),
]

import math

for fn_name, cls, kind_ident, comp_str, mrule_tp, mrule_rs, param_ref, points in test_cases:
    comps = comp_str.split(",")
    comps_rs = ", ".join(f'"{c}"' for c in comps)
    print(f"Generating {fn_name} for {comp_str} ({mrule_tp}, ref={param_ref})...")
    if param_ref != "DEFAULT":
        eos = cls(comp_str, mixing=mrule_tp, parameter_reference=param_ref)
    else:
        eos = cls(comp_str, mixing=mrule_tp)
    lines.append("#[test]")
    lines.append(f"fn {fn_name}() {{")
    lines.append(f"    let options = CubicOptions {{")
    lines.append(f"        mixing_rule: MixingRule::{mrule_rs},")
    if param_ref != "DEFAULT":
        lines.append(f"        parameter_reference: \"{param_ref}\",")
    lines.append(f"        ..Default::default()")
    lines.append(f"    }};")
    lines.append(f"    let eos = Cubic::with_options(CubicKind::{kind_ident}, &[{comps_rs}], options).unwrap();")
    lines.append(f"    assert_eq!(eos.mixing_rule, MixingRule::{mrule_rs});\n")

    for T, V, z in points:
        P = eos.pressure_tv(T, V, z)[0]
        lnphi, = eos.thermo_tvp(T, V, z)
        z_rs = ", ".join(str(x) for x in z)
        p_tol = 1e-4 * max(1.0, abs(P))
        lines.append(f"    // Point: T = {T} K, V = {V} m^3/mol, z = [{z_rs}]")
        lines.append(f"    let prep = eos.prepare({T:.2f}, &[{z_rs}]).unwrap();")
        lines.append(f"    let p_res = prep.pressure({V:.6e}).unwrap();")
        lines.append(f"    assert!((p_res.value - {P:.16e}).abs() < {p_tol:.16e}, \"P diff: {{}}\", (p_res.value - {P:.16e}).abs());")
        if all(math.isfinite(val) for val in lnphi) and P > 0:
            lines.append(f"    let mut lnphi = vec![0.0; {len(lnphi)}];")
            lines.append(f"    prep.ln_fugacity_into({V:.6e}, &mut lnphi).unwrap();")
            for i, val in enumerate(lnphi):
                lines.append(f"    assert!((lnphi[{i}] - {float(val):.16e}).abs() < 1e-4, \"lnphi[{i}] diff: {{}}\", (lnphi[{i}] - {float(val):.16e}).abs());")
        lines.append("")
    lines.append("}\n")

target = ROOT / "tests/excess_gibbs.rs"
with open(target, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
print(f"Generated {target}.")
