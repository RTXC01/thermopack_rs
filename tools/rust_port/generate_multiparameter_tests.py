"""Generate tests/multiparameter.rs against .reference/thermopack.dll."""
import sys
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/rust_port"))
from reference import load

dll = load(str(ROOT / ".toolchains/gcc14/mingw64/bin"))
from thermopack.multiparameter import multiparam

lines = []
lines.append("//! Integration tests for NIST Multiparameter Equations of State.")
lines.append("//! Generated by tools/rust_port/generate_multiparameter_tests.py against .reference/thermopack.dll.")
lines.append("//! Copyright thermotools and Contributors. Apache-2.0.\n")
lines.append("#![allow(clippy::excessive_precision)]\n")
lines.append("use thermopack_rs::{Multiparameter, Phase};\n")

fluids = [
    ("test_multiparameter_c3", "C3", [
        (300.0, 0.001),
        (350.0, 0.0005),
        (400.0, 0.0002),
        (250.0, 7.900109743919106e-05),
    ]),
    ("test_multiparameter_r134a", "R134A", [
        (300.0, 0.001),
        (350.0, 0.0003),
        (400.0, 0.0001),
    ]),
    ("test_multiparameter_normal_h2", "N-H2", [
        (30.0, 0.0005),
        (50.0, 0.001),
        (100.0, 0.002),
    ]),
    ("test_multiparameter_ortho_h2", "O-H2", [
        (30.0, 0.0005),
        (60.0, 0.001),
    ]),
    ("test_multiparameter_para_h2", "P-H2", [
        (30.0, 0.0005),
        (60.0, 0.001),
    ]),
]

for fn_name, fluid_ident, points in fluids:
    print(f"Generating {fn_name} for {fluid_ident}...")
    eos = multiparam(fluid_ident, "NIST_MEOS")
    lines.append("#[test]")
    lines.append(f"fn {fn_name}() {{")
    lines.append(f'    let eos = Multiparameter::new("{fluid_ident}").unwrap();')
    lines.append(f'    assert_eq!(eos.record().ident, "{fluid_ident}");\n')

    for T, V in points:
        P, = eos.pressure_tv(T, V, [1.0])
        H, = eos.enthalpy_tv(T, V, [1.0])
        S, = eos.entropy_tv(T, V, [1.0])
        lnphi, = eos.thermo_tvp(T, V, [1.0])

        p_tol = max(1e-4 * abs(P), 1.0)
        h_tol = max(1e-4 * abs(H), 1.0)
        s_tol = 1e-4 * max(abs(S), 1.0)

        lines.append(f"    // Point: T = {T} K, V = {V:.6e} m^3/mol")
        lines.append(f"    let prep = eos.prepare({T:.2f}).unwrap();")
        lines.append(f"    let p_res = prep.pressure({V:.16e}).unwrap();")
        lines.append(f"    assert!((p_res.value - {P:.16e}).abs() < {p_tol:.16e}, \"P diff: {{}}\", (p_res.value - {P:.16e}).abs());")
        lines.append(f"    let h = prep.enthalpy({V:.16e}).unwrap();")
        lines.append(f"    assert!((h - {H:.16e}).abs() < {h_tol:.16e}, \"H diff: {{}}\", (h - {H:.16e}).abs());")
        lines.append(f"    let s = prep.entropy({V:.16e}).unwrap();")
        lines.append(f"    assert!((s - {S:.16e}).abs() < {s_tol:.16e}, \"S diff: {{}}\", (s - {S:.16e}).abs());")
        if math.isfinite(lnphi[0]) and P > 0:
            lines.append(f"    let lnphi = prep.ln_fugacity({V:.16e}).unwrap();")
            lines.append(f"    assert!((lnphi - {lnphi[0]:.16e}).abs() < 1e-4, \"lnphi diff: {{}}\", (lnphi - {lnphi[0]:.16e}).abs());")
        lines.append("")

    lines.append("}\n")

# Add volume solving test
lines.append("""#[test]
fn test_multiparameter_c3_volume_solving() {
    let eos = Multiparameter::new("C3").unwrap();
    let prep_liq = eos.prepare(250.0).unwrap();
    let v_liq = prep_liq.volume(1.0e5, Phase::Liquid).unwrap();
    let p_liq = prep_liq.pressure(v_liq).unwrap();
    assert!((p_liq.value - 1.0e5).abs() < 1.0, "Liquid P diff: {}", (p_liq.value - 1.0e5).abs());

    let prep_vap = eos.prepare(350.0).unwrap();
    let v_vap = prep_vap.volume(1.0e5, Phase::Vapor).unwrap();
    let p_vap = prep_vap.pressure(v_vap).unwrap();
    assert!((p_vap.value - 1.0e5).abs() < 1.0, "Vapor P diff: {}", (p_vap.value - 1.0e5).abs());
}
""")

target = ROOT / "tests/multiparameter.rs"
with open(target, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
print(f"Generated {target}.")
