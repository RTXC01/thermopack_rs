"""Generate rust/src/excess_gibbs_data.rs from mixdatadb.f90."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
mixdatadb = ROOT / "src/mixdatadb.f90"

with open(mixdatadb, "r", encoding="utf-8") as f:
    text = f.read()

chunks = text.split("type (interGEdatadb), parameter ::")[1:]
parsed = []
for ch in chunks:
    m = re.search(r"(\w+)\s*=\s*&?\s*interGEdatadb\((.*?)\n\s*\)", ch, re.DOTALL)
    if not m:
        continue
    name = m.group(1)
    body = m.group(2).replace("&", "").replace("\n", " ")
    eosid = re.search(r'eosid\s*=\s*"([^"]+)"', body).group(1)
    mruleid = re.search(r'mruleid\s*=\s*"([^"]+)"', body).group(1)
    ref = re.search(r'ref\s*=\s*"([^"]+)"', body).group(1)
    bib_m = re.search(r'bib_ref\s*=\s*"([^"]*)"', body)
    bib = bib_m.group(1) if bib_m else ""
    uid1 = re.search(r'uid1\s*=\s*"([^"]+)"', body).group(1)
    uid2 = re.search(r'uid2\s*=\s*"([^"]+)"', body).group(1)
    kij = float(re.search(r"kijvalue\s*=\s*([\d\.e\+\-]+)", body).group(1))
    corr = int(re.search(r"correlation\s*=\s*(\d+)", body).group(1))
    alpha = [float(x.strip()) for x in re.search(r"alphaijvalue\s*=\s*\(\/(.*?)\/\)", body).group(1).split(",")]
    polyij = [float(x.strip()) for x in re.search(r"polyij\s*=\s*\(\/(.*?)\/\)", body).group(1).split(",")]
    polyji = [float(x.strip()) for x in re.search(r"polyji\s*=\s*\(\/(.*?)\/\)", body).group(1).split(",")]
    parsed.append({
        "name": name,
        "eosid": eosid,
        "mruleid": mruleid,
        "ref": ref,
        "bib_ref": bib,
        "uid1": uid1,
        "uid2": uid2,
        "kij": kij,
        "correlation": corr,
        "alpha": alpha,
        "polyij": polyij,
        "polyji": polyji,
    })

print(f"Parsed {len(parsed)} interGE records.")

out = []
out.append("//! Source-derived Excess Gibbs / Huron-Vidal binary interaction database.")
out.append("//! Automatically generated by tools/rust_port/generate_excess_gibbs_data.py from src/mixdatadb.f90.")
out.append("//! Copyright thermotools and Contributors. Apache-2.0.\n")
out.append("#![allow(clippy::excessive_precision)]\n")

out.append("/// Excess Gibbs energy model correlation form.")
out.append("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
out.append("pub enum GeCorrelation {")
out.append("    /// Polynomial in temperature (tau = a/T + b + cT).")
out.append("    Polynomial,")
out.append("    /// Maribo-Mogensen temperature correlation.")
out.append("    MariboMogensen,")
out.append("}\n")

out.append("/// Record for binary excess Gibbs parameters.")
out.append("#[derive(Debug, Clone, Copy)]")
out.append("pub struct ExcessGibbsRecord {")
out.append("    pub eos_id: &'static str,")
out.append("    pub mrule_id: &'static str,")
out.append("    pub reference: &'static str,")
out.append("    pub bib_reference: &'static str,")
out.append("    pub uid1: &'static str,")
out.append("    pub uid2: &'static str,")
out.append("    pub kij: f64,")
out.append("    pub correlation: GeCorrelation,")
out.append("    pub alpha_ij: [f64; 2],")
out.append("    pub poly_ij: [f64; 3],")
out.append("    pub poly_ji: [f64; 3],")
out.append("}\n")

out.append(f"/// All {len(parsed)} source-derived excess Gibbs binary interaction records.")
out.append(f"pub static EXCESS_GIBBS_RECORDS: [ExcessGibbsRecord; {len(parsed)}] = [")
for r in parsed:
    corr_str = "GeCorrelation::Polynomial" if r["correlation"] == 1 else "GeCorrelation::MariboMogensen"
    out.append("    ExcessGibbsRecord {")
    out.append(f'        eos_id: "{r["eosid"]}",')
    out.append(f'        mrule_id: "{r["mruleid"]}",')
    out.append(f'        reference: "{r["ref"]}",')
    out.append(f'        bib_reference: "{r["bib_ref"]}",')
    out.append(f'        uid1: "{r["uid1"]}",')
    out.append(f'        uid2: "{r["uid2"]}",')
    out.append(f'        kij: {r["kij"]:.10e},')
    out.append(f'        correlation: {corr_str},')
    out.append(f'        alpha_ij: [{r["alpha"][0]:.10e}, {r["alpha"][1]:.10e}],')
    out.append(f'        poly_ij: [{r["polyij"][0]:.10e}, {r["polyij"][1]:.10e}, {r["polyij"][2]:.10e}],')
    out.append(f'        poly_ji: [{r["polyji"][0]:.10e}, {r["polyji"][1]:.10e}, {r["polyji"][2]:.10e}],')
    out.append("    },")
out.append("];\n")

out.append("""/// Lookup binary excess Gibbs parameters for a component pair.
/// Returns the record and a boolean indicating whether (uid1, uid2) is swapped relative to the record.
pub fn lookup_excess_gibbs(
    eos: &str,
    mrule: &str,
    uid1: &str,
    uid2: &str,
    preferred_ref: Option<&str>,
) -> Option<(&'static ExcessGibbsRecord, bool)> {
    let u1 = uid1.to_ascii_uppercase();
    let u2 = uid2.to_ascii_uppercase();
    let eos_up = eos.to_ascii_uppercase();
    let mrule_up = mrule.to_ascii_uppercase();

    let target_ref = preferred_ref.unwrap_or("DEFAULT").trim().to_ascii_uppercase();
    let mut best_explicit: Option<(&'static ExcessGibbsRecord, bool)> = None;
    let mut default_entry: Option<(&'static ExcessGibbsRecord, bool)> = None;

    for r in &EXCESS_GIBBS_RECORDS {
        if !r.eos_id.eq_ignore_ascii_case(&eos_up) || !r.mrule_id.eq_ignore_ascii_case(&mrule_up) {
            continue;
        }
        let (matched, swapped) = if r.uid1.eq_ignore_ascii_case(&u1) && r.uid2.eq_ignore_ascii_case(&u2) {
            (true, false)
        } else if r.uid1.eq_ignore_ascii_case(&u2) && r.uid2.eq_ignore_ascii_case(&u1) {
            (true, true)
        } else {
            (false, false)
        };
        if !matched {
            continue;
        }

        let ref_up = r.reference.to_ascii_uppercase();
        if !target_ref.is_empty() && target_ref != "DEFAULT" && ref_up.contains(&target_ref) {
            best_explicit = Some((r, swapped));
            break;
        }
        if ref_up.contains("DEFAULT") {
            default_entry = Some((r, swapped));
        }
    }

    best_explicit.or(default_entry)
}
""")

target = ROOT / "rust/src/excess_gibbs_data.rs"
with open(target, "w", encoding="utf-8") as f:
    f.write("\n".join(out))
print(f"Generated {target} with {len(parsed)} records.")
