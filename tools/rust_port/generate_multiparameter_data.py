def parse_array(name, txt):
    m = re.search(r'::\s*' + name + r'\s*=\s*\((.*?)\)', txt, re.DOTALL)
    if not m:
        m = re.search(r'::\s*' + name + r'\s*=\s*(.*?)\n', txt)
    if not m:
        return []
    raw = m.group(1).replace('&', '').replace('/', '').replace('\n', ' ')
    parts = [x.strip() for x in raw.split(',') if x.strip()]
    res = []
    for x in parts:
        try:
            if '.' in x or 'e' in x.lower() or '-' in x:
                res.append(float(x))
            else:
                res.append(int(x))
        except ValueError:
            res.append(float(x))
    return res

def parse_scalar(pattern, txt, cast=float):
    m = re.search(pattern, txt)
    if m:
        return cast(m.group(1))
    return None

