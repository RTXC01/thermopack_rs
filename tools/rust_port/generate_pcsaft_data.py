"""Generate Rust constants for PC-SAFT pure component and binary interaction data."""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]

EOS_MAP = {
    "eospc_saft": "PC-SAFT",
    "eosopc_saft": "OPC-SAFT",
    "eosspc_saft": "sPC-SAFT",
    "eospcp_saft": "PCP-SAFT",
    "eosspcp_saft": "sPCP-SAFT",
}

SCHEME_MAP = {
    "no_assoc": "AssocScheme::NoAssoc",
    "assoc_scheme_1": "AssocScheme::Scheme1",
    "assoc_scheme_2a": "AssocScheme::Scheme2A",
    "assoc_scheme_2b": "AssocScheme::Scheme2B",
    "assoc_scheme_2c": "AssocScheme::Scheme2C",
    "assoc_scheme_3a": "AssocScheme::Scheme3A",
    "assoc_scheme_3b": "AssocScheme::Scheme3B",
    "assoc_scheme_4a": "AssocScheme::Scheme4A",
    "assoc_scheme_4b": "AssocScheme::Scheme4B",
    "assoc_scheme_4c": "AssocScheme::Scheme4C",
    "assoc_scheme_1ea": "AssocScheme::Scheme1ea",
}

COMB_RULE_MAP = {
    "defaultcomb": "AssocCombRule::DefaultComb",
    "aricomb": "AssocCombRule::AriComb",
    "geocomb": "AssocCombRule::GeoComb",
}


def number(value):
    v = float(str(value).replace("D", "e").replace("d", "e"))
    assert v == v and abs(v) != float("inf")
    return repr(v)


def string(value):
    return json.dumps(str(value))


def parse_db():
    source = (ROOT / "src/pc_saft_datadb.f90").read_text(encoding="utf-8")

    pure_records = []
    for var, body in re.findall(r"(PCcx\d+)\s*=\s*&?\s*pc_saft_data\((.*?)\n\s*\)", source, re.S):
        clean_body = re.sub(r"&(?:\s*[\r\n]+\s*&?)?", " ", body)
        fields = {}
        for k, v in re.findall(r'(\w+)\s*=\s*("[^"]*"|[^,)]+)', clean_body):
            fields[k.strip().lower()] = v.strip()
        eos_key = fields["eosidx"].lower()
        assert eos_key in EOS_MAP, f"Unknown PC-SAFT eosidx: {fields['eosidx']}"
        scheme_key = fields["assoc_scheme"].lower()
        assert scheme_key in SCHEME_MAP, f"Unknown PC-SAFT assoc_scheme: {fields['assoc_scheme']}"
        pure_records.append(
            {
                "var": var,
                "eos": EOS_MAP[eos_key],
                "ident": fields.get("compname", "").strip('"'),
                "m": number(fields["m"]),
                "sigma": number(fields["sigma"]),
                "eps_depth_divk": number(fields["eps_depth_divk"]),
                "eps": number(fields["eps"]),
                "beta": number(fields["beta"]),
                "assoc_scheme": SCHEME_MAP[scheme_key],
                "mu": number(fields["mu"]),
                "q": number(fields["q"]),
                "ref": fields.get("ref", "").strip('"'),
            }
        )

    binary_records = []
    for var, body in re.findall(r"(PCSAFT_KIJ_\d+)\s*=\s*&?\s*PCkijdata\((.*?)\n\s*\)", source, re.S):
        clean_body = re.sub(r"&(?:\s*[\r\n]+\s*&?)?", " ", body)
        fields = {}
        for k, v in re.findall(r'(\w+)\s*=\s*("[^"]*"|[^,)]+)', clean_body):
            fields[k.strip().lower()] = v.strip()
        eos_key = fields["eosidx"].lower()
        assert eos_key in EOS_MAP, f"Unknown PC-SAFT binary eosidx: {fields['eosidx']}"
        eps_rule = fields.get("eps_comb_rule", "defaultComb").lower()
        beta_rule = fields.get("beta_comb_rule", "defaultComb").lower()
        assert eps_rule in COMB_RULE_MAP, f"Unknown eps_comb_rule: {eps_rule}"
        assert beta_rule in COMB_RULE_MAP, f"Unknown beta_comb_rule: {beta_rule}"
        binary_records.append(
            {
                "var": var,
                "eos": EOS_MAP[eos_key],
                "uid1": fields.get("uid1", "").strip('"'),
                "uid2": fields.get("uid2", "").strip('"'),
                "kij": number(fields["kijvalue"]),
                "eps_comb_rule": COMB_RULE_MAP[eps_rule],
                "beta_comb_rule": COMB_RULE_MAP[beta_rule],
                "ref": fields.get("ref", "").strip('"'),
            }
        )
    return pure_records, binary_records


def generate():
    pure, binary = parse_db()
    lines = [
        "// Generated by tools/rust_port/generate_pcsaft_data.py; do not edit.",
        "// Copyright thermotools and Contributors. Apache-2.0.",
        "",
        "use crate::association::{AssocCombRule, AssocScheme};",
        "",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct PcSaftRecord {",
        "    pub ident: &'static str,",
        "    pub m: f64,",
        "    pub sigma: f64,",
        "    pub eps_depth_divk: f64,",
        "    pub reference: &'static str,",
        "    pub eos: &'static str,",
        "    pub eps: f64,",
        "    pub beta: f64,",
        "    pub assoc_scheme: AssocScheme,",
        "    pub mu: f64,",
        "    pub q: f64,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct PcSaftKijRecord {",
        "    pub uid1: &'static str,",
        "    pub uid2: &'static str,",
        "    pub kij: f64,",
        "    pub reference: &'static str,",
        "    pub eos: &'static str,",
        "    pub eps_comb_rule: AssocCombRule,",
        "    pub beta_comb_rule: AssocCombRule,",
        "}",
        "",
        "pub(super) const PURE_RECORDS: &[PcSaftRecord] = &[",
    ]
    for r in pure:
        lines.extend(
            [
                "    PcSaftRecord {",
                f"        ident: {string(r['ident'])},",
                f"        m: {r['m']},",
                f"        sigma: {r['sigma']},",
                f"        eps_depth_divk: {r['eps_depth_divk']},",
                f"        reference: {string(r['ref'])},",
                f"        eos: {string(r['eos'])},",
                f"        eps: {r['eps']},",
                f"        beta: {r['beta']},",
                f"        assoc_scheme: {r['assoc_scheme']},",
                f"        mu: {r['mu']},",
                f"        q: {r['q']},",
                "    },",
            ]
        )
    lines.append("];")
    lines.append("")
    lines.append("pub(super) const KIJ_RECORDS: &[PcSaftKijRecord] = &[")
    for r in binary:
        lines.extend(
            [
                "    PcSaftKijRecord {",
                f"        uid1: {string(r['uid1'])},",
                f"        uid2: {string(r['uid2'])},",
                f"        kij: {r['kij']},",
                f"        reference: {string(r['ref'])},",
                f"        eos: {string(r['eos'])},",
                f"        eps_comb_rule: {r['eps_comb_rule']},",
                f"        beta_comb_rule: {r['beta_comb_rule']},",
                "    },",
            ]
        )
    lines.append("];")
    lines.append("")
    lines.append("pub fn pure_records() -> &'static [PcSaftRecord] {")
    lines.append("    PURE_RECORDS")
    lines.append("}")
    lines.append("")
    lines.append("pub fn kij_records() -> &'static [PcSaftKijRecord] {")
    lines.append("    KIJ_RECORDS")
    lines.append("}")
    lines.append("")
    lines.append("pub fn select_pc_saft_record(ident: &str, reference: &str) -> Option<&'static PcSaftRecord> {")
    lines.append("    crate::component::select_record(PURE_RECORDS, reference, |r| {")
    lines.append("        r.ident.eq_ignore_ascii_case(ident).then_some(r.reference)")
    lines.append("    })")
    lines.append("}")
    lines.append("")
    lines.append("pub fn select_pc_saft_kij_record(")
    lines.append("    uid1: &str,")
    lines.append("    uid2: &str,")
    lines.append("    reference: &str,")
    lines.append(") -> Option<&'static PcSaftKijRecord> {")
    lines.append("    crate::component::select_record(KIJ_RECORDS, reference, |r| {")
    lines.append("        let match_pair = (r.uid1.eq_ignore_ascii_case(uid1) && r.uid2.eq_ignore_ascii_case(uid2))")
    lines.append("            || (r.uid1.eq_ignore_ascii_case(uid2) && r.uid2.eq_ignore_ascii_case(uid1));")
    lines.append("        match_pair.then_some(r.reference)")
    lines.append("    })")
    lines.append("}")
    lines.append("")
    lines.append("pub fn select_pc_saft_kij(uid1: &str, uid2: &str, reference: &str) -> f64 {")
    lines.append("    select_pc_saft_kij_record(uid1, uid2, reference)")
    lines.append("        .map(|r| r.kij)")
    lines.append("        .unwrap_or(0.0)")
    lines.append("}")

    target = ROOT / "rust/src/pc_saft_data.rs"
    with target.open("w", encoding="utf-8", newline="\n") as out:
        out.write("\n".join(lines) + "\n")
    print(f"Generated {len(pure)} pure PC-SAFT records and {len(binary)} binary records in {target}")


if __name__ == "__main__":
    generate()
