"""Generate rust/src/solid_data.rs from src/solid_correlation_datadb.f90.

The melting and sublimation line correlations of the original fork are pure
data: 23 melting curves and 16 sublimation curves with their coefficients,
exponents, reducing parameters and reference information. The generated module
keeps the source order of the correlation arrays.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
source = ROOT / "src/solid_correlation_datadb.f90"
text = source.read_text(encoding="utf-8")


def strip_comments(text):
    out = []
    for line in text.splitlines():
        cleaned = []
        in_string = False
        for char in line:
            if char == '"':
                in_string = not in_string
                cleaned.append(char)
            elif char == "!" and not in_string:
                break
            else:
                cleaned.append(char)
        out.append("".join(cleaned))
    return "\n".join(out)


clean = strip_comments(text)

records = {}
for match in re.finditer(
    r"type\s*\(\s*solid_correlation_data\s*\)\s*,\s*parameter\s*::\s*(\w+)\s*=\s*&", clean
):
    name = match.group(1)
    start = clean.index("solid_correlation_data", match.end())
    start = clean.index("(", start)
    depth = 0
    index = start
    while index < len(clean):
        if clean[index] == "(":
            depth += 1
        elif clean[index] == ")":
            depth -= 1
            if depth == 0:
                break
        index += 1
    body = clean[start + 1 : index]

    def field(field_name):
        found = re.search(field_name + r"\s*=\s*([^,&]+)", body)
        if found is None:
            raise SystemExit(f"missing field {field_name} in {name}")
        return found.group(1).strip()

    def numbers(field_name):
        found = re.search(field_name + r"\s*=\s*\(\s*/([^/]*)/", body)
        if found is None:
            raise SystemExit(f"missing array {field_name} in {name}")
        values = found.group(1).replace("&", ",")
        return [float(value) for value in values.split(",") if value.strip()]

    def string(field_name):
        found = re.search(field_name + r'\s*=\s*"([^"]*)"', body)
        if found is None:
            raise SystemExit(f"missing string {field_name} in {name}")
        return found.group(1)

    records[name] = {
        "comp_name": string("compName"),
        "correlation": string("correlation"),
        "triple_temperature": float(field("triple_temperature")),
        "minimum_temperature": float(field("minimum_temperature")),
        "maximum_temperature": float(field("maximum_temperature")),
        "reducing_pressure": float(field("reducing_pressure")),
        "reducing_temperature": float(field("reducing_temperature")),
        "n_coeff": int(field("n_coeff")),
        "n_coeff_1": int(field("n_coeff_1")),
        "n_coeff_2": int(field("n_coeff_2")),
        "n_coeff_3": int(field("n_coeff_3")),
        "coeff": numbers("coeff"),
        "exponents": numbers("exponents"),
        "bib_ref": string("bib_ref"),
        "ref": string("ref"),
    }


def array_entries(parameter):
    """Return the record names of a correlation array in source order."""
    match = re.search(
        parameter + r"\s*=\s*\(\s*/&(.*?)/\)", clean, re.S
    )
    if match is None:
        raise SystemExit(f"missing array {parameter}")
    return [
        name.strip()
        for name in match.group(1).replace("&", ",").split(",")
        if name.strip()
    ]


melting_names = array_entries("melting_corr_array")
sublimation_names = array_entries("sublimation_corr_array")
n_melting = int(re.search(r"n_melting_curves\s*=\s*(\d+)", clean).group(1))
n_sublimation = int(re.search(r"n_sublimation_curves\s*=\s*(\d+)", clean).group(1))
if len(melting_names) != n_melting:
    raise SystemExit(f"expected {n_melting} melting curves, found {len(melting_names)}")
if len(sublimation_names) != n_sublimation:
    raise SystemExit(
        f"expected {n_sublimation} sublimation curves, found {len(sublimation_names)}"
    )
for name in melting_names + sublimation_names:
    if name not in records:
        raise SystemExit(f"missing record {name}")

out = []
def number(value):
    """Format a double so that it round-trips exactly.

    The source tables carry up to thirteen significant digits, so a fixed
    format would silently drop the difference between two coefficients.
    """
    text = repr(float(value))
    if float(text) != float(value):
        raise SystemExit(f"value {value} does not round-trip")
    return text


out.append("//! Source-derived melting and sublimation line correlations.")
out.append("//! Automatically generated by tools/rust_port/generate_solid_data.py")
out.append("//! from src/solid_correlation_datadb.f90.")
out.append("//! Copyright thermotools and Contributors. Apache-2.0.\n")
out.append("#![allow(clippy::excessive_precision)]\n")
out.append("/// Parameters of a melting or sublimation line correlation.")
out.append("#[derive(Debug, Clone, Copy)]")
out.append("pub struct SolidCorrelation {")
out.append("    /// Component identifier of the correlation.")
out.append("    pub comp_name: &'static str,")
out.append("    /// Correlation label, for example ML-1 or SL-2.")
out.append("    pub correlation: &'static str,")
out.append("    /// Triple point temperature in K.")
out.append("    pub triple_temperature: f64,")
out.append("    /// Lowest temperature of the sublimation line in K.")
out.append("    pub minimum_temperature: f64,")
out.append("    /// Highest temperature of the melting line in K.")
out.append("    pub maximum_temperature: f64,")
out.append("    /// Pressure scaling parameter in Pa.")
out.append("    pub reducing_pressure: f64,")
out.append("    /// Temperature scaling parameter in K.")
out.append("    pub reducing_temperature: f64,")
out.append("    /// Number of coefficients.")
out.append("    pub n_coeff: usize,")
out.append("    /// Number of coefficients of the reduced temperature terms.")
out.append("    pub n_coeff_1: usize,")
out.append("    /// Number of coefficients of the one-minus-reduced-temperature terms.")
out.append("    pub n_coeff_2: usize,")
out.append("    /// Number of coefficients of the logarithmic terms.")
out.append("    pub n_coeff_3: usize,")
out.append("    /// Correlation coefficients.")
out.append("    pub coeff: [f64; 6],")
out.append("    /// Correlation exponents.")
out.append("    pub exponents: [f64; 6],")
out.append("    /// Bibliographic reference of the correlation.")
out.append("    pub bib_ref: &'static str,")
out.append("    /// Parameter set of the correlation.")
out.append("    pub ref_: &'static str,")
out.append("}\n")


def emit(name, entries):
    out.append(f"/// The {len(entries)} source-derived {name} correlations.")
    out.append(
        f"pub static {name.upper()}_CORRELATIONS: [SolidCorrelation; {len(entries)}] = ["
    )
    for entry in entries:
        record = records[entry]
        out.append("    SolidCorrelation {")
        out.append(f'        comp_name: "{record["comp_name"]}",')
        out.append(f'        correlation: "{record["correlation"]}",')
        out.append(f'        triple_temperature: {number(record["triple_temperature"])},')
        out.append(f'        minimum_temperature: {number(record["minimum_temperature"])},')
        out.append(f'        maximum_temperature: {number(record["maximum_temperature"])},')
        out.append(f'        reducing_pressure: {number(record["reducing_pressure"])},')
        out.append(f'        reducing_temperature: {number(record["reducing_temperature"])},')
        out.append(f'        n_coeff: {record["n_coeff"]},')
        out.append(f'        n_coeff_1: {record["n_coeff_1"]},')
        out.append(f'        n_coeff_2: {record["n_coeff_2"]},')
        out.append(f'        n_coeff_3: {record["n_coeff_3"]},')
        coeff = ", ".join(number(value) for value in record["coeff"])
        out.append(f"        coeff: [{coeff}],")
        exponents = ", ".join(number(value) for value in record["exponents"])
        out.append(f"        exponents: [{exponents}],")
        out.append(f'        bib_ref: "{record["bib_ref"]}",')
        out.append(f'        ref_: "{record["ref"]}",')
        out.append("    },")
    out.append("];\n")


emit("melting", melting_names)
emit("sublimation", sublimation_names)

out.append("""/// Look up a melting line correlation by component identifier.
pub fn lookup_melting_correlation(comp_name: &str) -> Option<&'static SolidCorrelation> {
    MELTING_CORRELATIONS
        .iter()
        .find(|record| record.comp_name == comp_name)
}

/// Look up a sublimation line correlation by component identifier.
pub fn lookup_sublimation_correlation(comp_name: &str) -> Option<&'static SolidCorrelation> {
    SUBLIMATION_CORRELATIONS
        .iter()
        .find(|record| record.comp_name == comp_name)
}
""")

target = ROOT / "rust/src/solid_data.rs"
target.write_text("\n".join(out), encoding="utf-8")
print(
    f"Generated {target} with {len(melting_names)} melting and "
    f"{len(sublimation_names)} sublimation correlations."
)
for name in melting_names:
    record = records[name]
    print(f"  melt {record['comp_name']:>8} {record['correlation']}")
for name in sublimation_names:
    record = records[name]
    print(f"  subl {record['comp_name']:>8} {record['correlation']}")
